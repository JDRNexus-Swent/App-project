package com.github.se.jdrnexus.model.repository

import com.github.se.jdrnexus.ui.dice.DiceRollResult
import com.google.firebase.firestore.FirebaseFirestore
import com.google.firebase.firestore.Query
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.firstOrNull
import kotlinx.coroutines.tasks.await

/** Data class representing a dice roll as it is stored in Cloud Firestore. */
data class DiceRollEntity(
    val id: String = "",
    val userId: String = "",
    val username: String = "",
    val diceType: String = "",
    val modifier: Int = 0,
    val totalValue: Int = 0,
    val timestamp: Long = System.currentTimeMillis(), // Used to sort rolls by recency.
)

/**
 * Function to map a DiceRollResult to a DiceRollEntity. Extracts the mapping logic to keep the
 * repository clean.
 *
 * @param user The authenticated AuthUser who performed the roll.
 * @return A mapped DiceRollEntity ready to be saved in Firestore.
 */
fun DiceRollResult.toEntity(user: AuthUser): DiceRollEntity {
  return DiceRollEntity(
      userId = user.uid,
      username = user.username ?: "Unknown Player",
      diceType = this.diceType.name,
      modifier = this.modifier,
      totalValue = this.totalValue,
      timestamp = System.currentTimeMillis(),
  )
}

/** Repository responsible for handling dice roll data operations in Cloud Firestore. */
class DiceRepositoryFirestore(
    private val firestore: FirebaseFirestore,
    private val authRepository: AuthRepository,
) {

  companion object {
    // Must match the collection name used in GroupRepositoryFirestore
    private const val GROUPS_COLLECTION_PATH = "campaign_groups"
    // Name of the sub-collection inside each group document
    private const val DICE_ROLLS_SUBCOLLECTION = "dice_rolls"
  }

  /**
   * Saves a dice roll result to Firestore under the group’s dice_rolls subcollection.
   *
   * @param groupId The ID of the campaign/group.
   * @param rollResult The result generated by the DiceLogic.
   * @return A Result object indicating success or containing an Exception on failure.
   */
  suspend fun saveRollResult(groupId: String, rollResult: DiceRollResult): Result<Unit> {
    return try {
      // Retrieve the latest known state of the authenticated user
      val currentUser =
          authRepository.authState.firstOrNull()
              ?: return Result.failure(Exception("User is not authenticated"))

      val entity = rollResult.toEntity(currentUser)

      // Path to subcollection: campaign_groups/{groupId}/dice_rolls
      firestore
          .collection(GROUPS_COLLECTION_PATH)
          .document(groupId)
          .collection(DICE_ROLLS_SUBCOLLECTION)
          .add(entity)
          .await()

      Result.success(Unit)
    } catch (e: Exception) {
      Result.failure(e)
    }
  }

  /**
   * Retrieves a one-time list of dice rolls for a specific group. Useful for screens that need the
   * history but don't need real-time updates.
   *
   * @param groupId The ID of the campaign/group.
   * @return A Result containing the list of DiceRollEntity, ordered by newest first.
   */
  suspend fun getDiceRollsHistory(groupId: String): Result<List<DiceRollEntity>> {
    return try {
      val snapshot =
          firestore
              .collection(GROUPS_COLLECTION_PATH)
              .document(groupId)
              .collection(DICE_ROLLS_SUBCOLLECTION)
              .orderBy("timestamp", Query.Direction.DESCENDING)
              .get() // .get() fetches the data once instead of listening
              .await()

      val rolls =
          snapshot.documents.mapNotNull { doc ->
            doc.toObject(DiceRollEntity::class.java)?.copy(id = doc.id)
          }
      Result.success(rolls)
    } catch (e: Exception) {
      Result.failure(e)
    }
  }

  /**
   * Retrieves a real-time stream of dice rolls for a specific group. Uses Kotlin Flow to emit
   * updates whenever the Firestore sub-collection changes. The results are ordered by timestamp
   * (newest first).
   *
   * @param groupId The ID of the campaign/group to listen to.
   * @return A Flow emitting a list of DiceRollEntity.
   */
  fun getDiceRollsStream(groupId: String): Flow<List<DiceRollEntity>> = callbackFlow {
    val query =
        firestore
            .collection(GROUPS_COLLECTION_PATH)
            .document(groupId)
            .collection(DICE_ROLLS_SUBCOLLECTION)
            .orderBy("timestamp", Query.Direction.DESCENDING)

    // Listen for real-time updates from Firestore
    val listenerRegistration = query.addSnapshotListener { snapshot, error ->
      if (error != null) {
        close(error)
        return@addSnapshotListener
      }

      if (snapshot != null) {
        val rolls =
            snapshot.documents.mapNotNull { doc ->
              doc.toObject(DiceRollEntity::class.java)?.copy(id = doc.id)
            }
        trySend(rolls)
      }
    }
    // Clean up the listener when the flow collection is cancelled
    awaitClose { listenerRegistration.remove() }
  }
}
